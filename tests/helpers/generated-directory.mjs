import { rmSync } from 'node:fs'
import { dirname, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const generatedRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../.generated')

/** Resolves a fixture directory under tests/.generated without touching it. */
export const generatedDirectory = (name) => {
  const directory = resolve(generatedRoot, name)
  if (!directory.startsWith(`${generatedRoot}${sep}`)) {
    throw new Error(`refusing to use a fixture outside tests/.generated: ${name}`)
  }
  return directory
}

/**
 * Removes a fixture directory so the generator, which never deletes anything,
 * can write into it. Deletion is confined to tests/.generated by construction.
 */
export const clearGeneratedDirectory = (name) => {
  const directory = generatedDirectory(name)
  rmSync(directory, { force: true, recursive: true })
  return directory
}
